export interface ShapePiece {
  id: string;
  color: string;
  colorLight: string;
  colorDark: string;
  label: string; // for accessibility
  // Target position when assembled (relative to center, in percentage of container)
  targetX: number;
  targetY: number;
  // Scattered position when disassembled
  scatterX: number;
  scatterY: number;
  // SVG path or shape definition
  shape: 'rect' | 'wedge' | 'sector' | 'triangle' | 'layer';
  rotation: number;
  width: number;
  height: number;
}

